@lru_cache(maxsize=1)
def catalog():
    result = {}
    data_root = Path(__file__).resolve().parents[1] / 'data'
    approval_path = data_root / 'integration-approvals.json'
    approvals = json.loads(approval_path.read_text(encoding='utf-8')) if approval_path.exists() else {}
    for name in SOURCES:
        path = data_root / name
        if not path.exists():
            if name in approvals:
                raise ValueError('Approved integration source missing')
            continue
        raw = path.read_bytes()
        approval = approvals.get(name)
        if approval and hashlib.sha256(raw).hexdigest() != approval['sha256']:
            raise ValueError('Approved integration source hash mismatch')
        for question in json.loads(raw.decode('utf-8-sig')):
            if approval:
                if question['id'] not in approval['question_ids']:
                    continue
                # Publish an independently reviewed exact source without changing its bytes.
                question = dict(question, review_status='reviewed')
            if question.get('review_status') != 'reviewed':
                continue
            validate_payload_text(question)
            contract = question.get('exercise', {})
            if (not all(label in question.get('body', '') for label in ('操作任务', '产物', '验收方法'))
                    or not contract.get('environment') or not contract.get('verification')
                    or not contract.get('deliverables') or not question.get('answer')):
                raise ValueError('发布的动手题缺少操作、产物、环境或验收合同')
            validate_files(question.get('files', {}))
            deliverables = contract['deliverables']
            if not isinstance(deliverables, list) or len(set(deliverables)) != len(deliverables):
                raise ValueError('动手题交付路径必须唯一')
            validate_files({name: '' for name in deliverables})
            if question['id'] in result:
                raise ValueError('动手题编号重复')
            result[question['id']] = question
    return result


@lru_cache(maxsize=1)
def historical_catalog():
    """Only packaged, reviewed contracts can authorize an old exam's execution."""
    path = Path(__file__).resolve().parents[1] / 'data/hands-on-history.json'
    if not path.exists():
        return {}
    result = {}
    for question in json.loads(path.read_text(encoding='utf-8')):
        validate_payload_text(question)
        if question.get('review_status') != 'reviewed':
            raise ValueError('历史验收合同必须经过审校')
        result[(question['id'], fingerprint(question))] = question
    return result


def trusted(question):
    original = catalog().get(question['id'])
    # Browsing decorates questions with learner state; this is not bank content.
    content = {k:v for k,v in question.items() if k not in ('learning', 'automatic_grading')}
    # Restoring or editing database JSON cannot grant executable assessment rights.
    if original and fingerprint(content) == fingerprint(original):
        return original
    return historical_catalog().get((question['id'], fingerprint(content)))


def manual_artifact_contract(question):
    """Only explicitly approved current contracts can await manual artifact review."""
    original = trusted(question)
    current = catalog().get(question.get('id'))
    if (not original or not current or original.get('assessment') or not original.get('exercise')
            or fingerprint(original) != fingerprint(current)):
        return False
    path = Path(__file__).resolve().parents[1] / 'data/integration-approvals.json'
    approvals = json.loads(path.read_text(encoding='utf-8')) if path.exists() else {}
    return any(original['id'] in row.get('manual_review_ids', []) for row in approvals.values())


def inspect_artifacts(question, files):
    validate_files(files)
    exercise = question.get('exercise', {})
    required = exercise.get('deliverables', [])
    checks = []
    for name in required:
        value = files.get(name)
        present = isinstance(value, str) and bool(value.strip())
        checks.append({'label': '提交产物：' + name, 'passed': present})
        if not present:
            continue
        try:
            if name.endswith('.json'):
                json.loads(value)
            elif name.endswith('.py'):
                ast.parse(value)
            else:
                continue
        except (ValueError, SyntaxError):
            checks.append({'label': name + ' 语法可解析', 'passed': False})
        else:
            checks.append({'label': name + ' 语法可解析', 'passed': True})
    if required:
        changed = any(files.get(name) != question.get('files', {}).get(name) for name in required)
        checks.append({'label': '已修改初始产物', 'passed': changed})
    failed = any(not check['passed'] for check in checks)
    return {'passed': False if failed else None, 'method': '产物检查',
            'stage': 'artifact_failed' if failed else 'awaiting_execution',
            'message': '产物检查未通过，请补齐或修正文件。' if failed else '产物已收到；语法检查不代表功能正确，仍需执行验收。',
            'checks': checks,
            'artifact_sha256': hashlib.sha256(json.dumps(files, sort_keys=True, ensure_ascii=False).encode()).hexdigest()}


def program_contract(question):
    original = trusted(question)
    assessment = original.get('assessment', {}) if original else {}
    if assessment.get('kind') != 'program':
        return None
    tests = assessment.get('test_files', {})
    validate_files(tests)
    if not tests or set(tests).intersection(original['exercise']['deliverables']) or set(tests).intersection(original.get('files', {})):
        raise ValueError('验收文件必须独立于学员提交产物')
    command = assessment.get('command')
    timeout = assessment.get('timeout', 30)
    if (not isinstance(command, str) or not command.strip() or len(command) > 24000
            or type(timeout) is not int or not 1 <= timeout <= 120):
        raise ValueError('验收命令或超时配置无效')
    return assessment


def distributed_contract(question):
    """Only an immutable reviewed contract may select the larger workspace."""
    original = trusted(question)
    return bool(original and original.get('exercise', {}).get('resource_profile') == 'distributed'
                and program_contract(question))


def cluster_contract(question):
    """Only a fingerprint-matched reviewed program may require a private cluster."""
    original = trusted(question)
    return bool(original and original.get('exercise', {}).get('workspace') == 'cluster'
                and program_contract(question))


