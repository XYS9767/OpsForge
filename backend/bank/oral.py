def apply(questions):
    for q in questions:
        if q["id"].startswith("interview-"):
            q["answer"] = CORE[q["id"].removeprefix("interview-")]
        elif q["id"].startswith("extra-"):
            slug, index = q["id"][6:].rsplit("-", 1)
            q["answer"] = EXTRA[slug][int(index)-1]
        if q["type"] == "interview":
            q["answer_style"] = "spoken"
    return questions
